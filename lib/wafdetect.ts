import type { Finding } from "./scanner";

/**
 * Détection passive de WAF / CDN et de défis anti-bot (CAPTCHA) à partir des
 * en-têtes et du corps de la réponse principale. Purement informatif : un WAF ou
 * un CAPTCHA ne sont pas des failles, mais ils faussent les autres contrôles
 * (réponses filtrées, pages de défi). On le signale pour que l'analyste le sache.
 *
 * Les signatures sont des marqueurs publics par lesquels ces produits s'identifient
 * (en-têtes, cookies, mentions dans la page) — des faits, pas des exploits.
 */

type Signature = { name: string; patterns: RegExp[] };

const WAF_SIGNATURES: Signature[] = [
  { name: "Cloudflare", patterns: [/\bcf-ray\b/i, /\b__cf(duid|_bm|uid)\b/i, /\bcloudflare\b/i, /attention required/i] },
  { name: "Akamai", patterns: [/\bak_bmsc\b/i, /\b_abck\b/i, /\bakamai(ghost)?\b/i, /\bx-akamai\b/i] },
  { name: "AWS WAF / ELB", patterns: [/\bawsalb\b/i, /\bx-amzn-(requestid|trace-id)\b/i, /\baws.?waf\b/i] },
  { name: "Imperva Incapsula", patterns: [/\bincap_ses\b/i, /\bvisid_incap\b/i, /\bimperva\b/i, /\bincapsula\b/i, /\bx-cdn:\s*incapsula/i] },
  { name: "Sucuri", patterns: [/\bx-sucuri(-id|-cache)?\b/i, /\bsucuri\b/i, /cloudproxy/i] },
  { name: "F5 BIG-IP ASM", patterns: [/\bbigipserver\b/i, /\bts[0-9a-f]{8}\b/i, /\bx-waf-(event|status)\b/i] },
  { name: "Barracuda", patterns: [/\bbarra_counter_session\b/i, /\bbarracuda\b/i] },
  { name: "Fastly", patterns: [/\bx-served-by:\s*cache/i, /\bfastly\b/i, /\bx-fastly\b/i] },
  { name: "Wordfence", patterns: [/\bwordfence\b/i, /generated by wordfence/i] },
  { name: "ModSecurity", patterns: [/\bmod_security\b/i, /\bmodsecurity\b/i, /this error was generated by mod_security/i] },
  { name: "StackPath / Highwinds", patterns: [/\bx-hw\b/i, /\bstackpath\b/i] },
  { name: "Azure Front Door", patterns: [/\bx-azure-ref\b/i, /\bx-fd-\w+/i] },
];

const CAPTCHA_SIGNATURES: Signature[] = [
  { name: "Cloudflare Turnstile", patterns: [/challenges\.cloudflare\.com\/turnstile/i, /cf-turnstile/i] },
  { name: "Cloudflare Challenge", patterns: [/cf-browser-verification/i, /checking your browser before accessing/i, /cf_chl_opt/i] },
  { name: "Google reCAPTCHA", patterns: [/www\.google\.com\/recaptcha/i, /\bg-recaptcha\b/i, /grecaptcha/i] },
  { name: "hCaptcha", patterns: [/\bhcaptcha\.com\b/i, /\bh-captcha\b/i] },
  { name: "Arkose Labs / FunCaptcha", patterns: [/arkoselabs\.com/i, /funcaptcha/i] },
  { name: "GeeTest", patterns: [/\bgeetest\b/i, /gt_captcha/i] },
];

/** Concatène en-têtes (clé:valeur), cookies et un extrait du corps pour la recherche. */
function haystack(headers: Headers, cookies: string[], body: string): string {
  const parts: string[] = [];
  headers.forEach((v, k) => parts.push(`${k}: ${v}`));
  parts.push(cookies.join(" "));
  parts.push(body.slice(0, 8000));
  return parts.join("\n");
}

function matchFirst(signatures: Signature[], text: string): string[] {
  return signatures.filter((s) => s.patterns.some((p) => p.test(text))).map((s) => s.name);
}

/** Findings WAF/CDN et CAPTCHA (0 à 2). `body` est le début du HTML de la page. */
export function detectWafCaptcha(headers: Headers, cookies: string[], body: string): Finding[] {
  const text = haystack(headers, cookies, body);
  const out: Finding[] = [];

  const wafs = matchFirst(WAF_SIGNATURES, text);
  if (wafs.length) {
    out.push({
      id: "waf",
      category: "Reconnaissance",
      title: `Pare-feu applicatif / CDN détecté : ${wafs.join(", ")}`,
      severity: "info",
      state: "info",
      detail:
        `La cible est protégée par ${wafs.join(", ")}. Les contrôles actifs peuvent être ` +
        "filtrés ou renvoyer des pages de blocage : interprétez les résultats en conséquence.",
      recommendation:
        "Pour un audit complet, placez Sentinel sur une liste d'autorisation du pare-feu, " +
        "ou testez depuis une IP de confiance afin d'éviter les faux négatifs.",
    });
  }

  const captchas = matchFirst(CAPTCHA_SIGNATURES, text);
  if (captchas.length) {
    out.push({
      id: "captcha",
      category: "Reconnaissance",
      title: `Défi anti-bot (CAPTCHA) détecté : ${captchas.join(", ")}`,
      severity: "info",
      state: "info",
      detail:
        `Un défi ${captchas.join(", ")} est présent. Les pages derrière ce défi ne sont pas ` +
        "analysées de façon fiable sans résolution manuelle du CAPTCHA.",
      recommendation:
        "Fournissez un accès de test sans CAPTCHA (compte dédié, contournement sur IP de test) " +
        "pour permettre l'analyse des pages protégées.",
    });
  }

  return out;
}
